/* Learn scenarios (#41) from the proven puzzle sets.

   tests/puzzles/<game>/puzzles.json holds positions whose optimal moves were PROVEN by the
   per-game solver, but tests/ is never deployed. This script picks a small, mixed set of
   them per game and writes it into client/learn/<game>-scenarios.js, a classic script that
   registers the data with `Learn.scenarios(game, [...])` and is listed in index.html.

   Only positions with the human to move (toMove 0, the seat a Learn scenario puts you in)
   and a value that is not already lost are used, so every scenario has something to find.
   The pick is deterministic: candidates are ordered by (bigger board first, then id) and
   taken tag by tag in TAGS order, round after round, until QUOTA is full. Re-running the
   script therefore never produces a diff unless the puzzle set changed.

   Run with `npm run learn:scenarios`. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { ROOT } from "../headless.mjs";
import { loadPuzzles, puzzleGames } from "../puzzles/runner.mjs";

const QUOTA = 8;

// tag -> the title a player sees; the order is also the picking order (most instructive first)
const TAGS = [
    ["win-in-1", "Win in one move"],
    ["avoid-trap", "Do not walk into the trap"],
    ["must-block", "Block the threat"],
    ["double-threat", "Make two threats at once"],
    ["win-in-2", "Win in two moves"],
    ["avoid-loss", "Only one move holds"],
    ["prefer-win", "Take the win, not the block"],
    ["win-in-3", "Win in three moves"],
    ["draw", "Hold the draw"],
    ["win-in-4", "Win in four moves"],
    ["win-in-5", "Win in five moves"],
    ["win-in-6", "Win in six moves"],
    ["separated", "Win the race for room"],
];
const TITLE = new Map(TAGS);
// tags that describe how a puzzle was produced, not what it teaches
const TOOLING = ["endgame-exhaustive", "opening"];

/* The generated notes are written for the puzzle tooling: they end in a sentence naming the
   board and the ply, count plies and say how the position was solved. Keep the ideas, drop
   the bookkeeping, and speak about the players instead of seat numbers. */
function clean(note) {
    const parts = String(note || "").split(/(?<=\.)\s+/);
    const kept = parts.filter((s) => !/moves played, player \d to move/.test(s) && !/^Solved exhaustively\.$/.test(s));
    return kept.join(" ")
        .replace(/\s*\(\d+\/\d+ moves are best\)/g, "")
        .replace(/\s*\(\d+ plies\)/g, "")
        .replace(/\bplayer 0\b/g, "you")
        .replace(/\bplayer 1\b/g, "the bot")
        .replace(/\s+/g, " ")
        .replace(/\s+\./g, ".")
        .trim();
}
// the tags a player is shown: the ones that name the idea, never the tooling ones
const shownTags = (tags) => tags.filter((t) => TITLE.has(t) && !TOOLING.includes(t));

export function pick(data) {
    const usable = data.puzzles
        // a Learn table always starts at seat 0 (Match.start numbers the game 1), so a puzzle
        // whose own config starts somebody else could not be replayed here
        .filter((p) => p.toMove === 0 && (p.config.startPlayer || 0) === 0 && p.value !== "loss" && Array.isArray(p.best) && p.best.length > 0)
        .sort((a, b) => (b.config.n - a.config.n) || (a.id < b.id ? -1 : 1));
    const out = [];
    const taken = new Set();
    for (let round = 0; out.length < QUOTA && round < QUOTA; round++) {
        for (const [tag] of TAGS) {
            if (out.length >= QUOTA) break;
            const hit = usable.find((p) => !taken.has(p.id) && p.tags.includes(tag));
            if (hit) { taken.add(hit.id); out.push({ tag, puzzle: hit }); }
        }
    }
    // a tag that comes round twice would give two rows the same name: number the later ones
    const seen = new Map();
    return out.map(({ tag, puzzle }) => ({
        id: puzzle.id,
        title: (() => { const k = (seen.get(tag) || 0) + 1; seen.set(tag, k); return k > 1 ? `${TITLE.get(tag)} (${k})` : TITLE.get(tag); })(),
        text: clean(puzzle.note),
        config: puzzle.config,
        history: puzzle.history,
        toMove: puzzle.toMove,
        best: puzzle.best,
        tags: shownTags(puzzle.tags),
    }));
}

function render(game, list, solver) {
    const rows = list.map((s) => `    ${JSON.stringify(s)},`).join("\n");
    return `/* Generated by scripts/learn/pick-scenarios.mjs — do not edit by hand.
   Training positions for the Learn section (#41), taken from the proven puzzle set
   tests/puzzles/${game}/puzzles.json (${solver.split(/[.;]/)[0].trim()}).
   Every "best" list is the complete set of optimal moves the solver proved. */

"use strict";

Learn.scenarios("${game}", [
${rows}
]);
`;
}

export function writeAll() {
    const dir = `${ROOT}client/learn/`;
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
    for (const game of puzzleGames()) {
        const data = loadPuzzles(game);
        const list = pick(data);
        const file = `${dir}${game}-scenarios.js`;
        const text = render(game, list, data.solver || "");
        const before = existsSync(file) ? readFileSync(file, "utf8") : "";
        writeFileSync(file, text);
        console.log(`${game}: ${list.length} scenarios -> client/learn/${game}-scenarios.js${before === text ? " (unchanged)" : ""}`);
        for (const s of list) console.log(`  ${s.id}  ${s.title}  [${s.tags.join(", ")}]`);
    }
}

// run as a script, not when a test imports `pick`
if (process.argv[1] && process.argv[1].endsWith("pick-scenarios.mjs")) writeAll();
